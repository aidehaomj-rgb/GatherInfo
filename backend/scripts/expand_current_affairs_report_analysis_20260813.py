def main() -> None:
    db = SessionLocal()
    try:
        report = db.get(Report, REPORT_ID)
        topic = db.get(Topic, report.topic_id) if report else None
        if not report or not topic:
            raise RuntimeError("report or topic missing")
        marker = "## 四、采集线索"
        if marker not in report.content:
            raise RuntimeError("report structure changed")
        head, cases = report.content.split(marker, 1)
        # Replace the former short action section with expanded cross-event analysis.
        head = head.split("## 三、优先核查动作", 1)[0].rstrip()
        report.content = f"{head}\n\n{ANALYSIS}\n\n## 七、采集线索{cases}"
        report.summary = "围绕10条涉进出口时政热点，新增两用物项、第三国转运和能源船舶风险传导分析，并提出0至7日、7至30日、30至90日分阶段处置方案及六类预警指标。"
        db.commit()
        files = export_report(report, {}, topic, formats=["md", "html", "pdf"])
        out_dir = Path(report.output_dir or Path(next(iter(files.values()))).parent)
        docx_path = out_dir / f"{report.title}.docx"
        write_docx(docx_path, report.title, report.content)
        report.output_files = {**files, "docx": str(docx_path)}
        db.commit()
        print({"report": report.id, "files": report.output_files})
    finally:
        db.close()


if __name__ == "__main__":
    main()
