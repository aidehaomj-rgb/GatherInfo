def _chinese_ordinal(value: int) -> str:
    digits = "零一二三四五六七八九"
    if value <= 10:
        return "十" if value == 10 else digits[value]
    if value < 20:
        return "十" + digits[value % 10]
    tens, ones = divmod(value, 10)
    return digits[tens] + "十" + (digits[ones] if ones else "")
def _topic_relevance_scores(
    db: Session,
    topic_id: str,
    item_ids: list[str],
) -> dict[str, float]:
    if not item_ids:
        return {}
    rows = db.query(
        ItemTopicMembership.item_id,
        ItemTopicMembership.relevance_score,
    ).filter(
        ItemTopicMembership.topic_id == topic_id,
        ItemTopicMembership.item_id.in_(item_ids),
        ItemTopicMembership.relevance_score.is_not(None),
    ).all()
    return {
        str(item_id): max(0.0, min(1.0, float(score)))
        for item_id, score in rows
    }


